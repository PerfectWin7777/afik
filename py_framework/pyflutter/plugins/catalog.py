SHIM_TEMPLATE = """import 'dart:async';

import 'package:pyflutter_dart_runtime/plugins/plugin_registry.dart';
// TODO: import 'package:{package}/{package}.dart';

/// Dispatch shim for `{package}`.
///
/// Read the package documentation, then map each Dart method you want to expose to a `case`
/// below. Rules: return only what the platform answered (never invent a successful result),
/// throw for anything unsupported, keep results simple (Map / List / String / bool / null).
class {class_name}Shim implements PyFlutterPlugin {{
  @override
  Future<dynamic> handleMethodCall(String method, Map<String, String> args) async {{
    switch (method) {{
      // case 'someMethod':
      //   final value = await SomeClass().someMethod(args['name'] ?? '');
      //   return {{'result': value}};
      default:
        throw UnsupportedError('{package} method "$method" is not supported.');
    }}
  }}
}}

/// Called by the generated installed_plugins.dart.
void register() {{
  PluginRegistry.register('{name}', {class_name}Shim());
}}
"""

PY_TEMPLATE = '''"""
PyFlutter {name} plugin (matches pub.dev package: {package}).
"""

from __future__ import annotations

from pyflutter.plugins.manager import call_plugin


# One Dart method = one snake_case Python method. A missing or malformed answer must
# read as a failure, never as a success.
def example() -> bool:
    """TODO: replace with the first mapped method."""
    res = call_plugin("{name}", "someMethod", {{}})
    return isinstance(res, dict) and res.get("result") is True
'''

TEST_TEMPLATE = '''"""Tests for the {name} plugin mapping."""

import unittest
from unittest.mock import patch

from pyflutter.plugins import {name}


class Test{class_name}(unittest.TestCase):
    def test_missing_or_malformed_answer_is_a_failure(self):
        for answer in (None, {{}}, "ok", []):
            with patch.object({name}, "call_plugin", return_value=answer):
                self.assertFalse({name}.example())


if __name__ == "__main__":
    unittest.main()
'''


def _class_name(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[_\-]", name))


def scaffold_plugin(name: str, runtime_dir: Path, py_framework_dir: Path, constraint: str = "any") -> list[Path]:
    """Creates the skeleton to map a new package (catalog entry, shim, Python module, test)."""
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise CatalogError(f"'{name}' is not a valid package name (lowercase letters, digits, underscores).")
    directory = catalog_dir(runtime_dir) / name
    if directory.exists():
        raise CatalogError(f"{directory} already exists.")
    directory.mkdir(parents=True)
    cls = _class_name(name)
    created = []
    (directory / "plugin.yaml").write_text(
        f"name: {name}\npackage: {name}\nconstraint: {constraint}\nshim: shim.dart\nfiles: [shim.dart]\n"
        f"registers: [{name}]\npython_module: pyflutter.plugins.{name}\n"
        "# android: {permissions: [], min_sdk: 0}\n# ios: {permissions: []}\n",
        encoding="utf-8",
    )
    created.append(directory / "plugin.yaml")
    (directory / "shim.dart").write_text(SHIM_TEMPLATE.format(package=name, name=name, class_name=cls), encoding="utf-8")
    created.append(directory / "shim.dart")
    py_file = py_framework_dir / "pyflutter" / "plugins" / f"{name}.py"
    if not py_file.exists():
        py_file.write_text(PY_TEMPLATE.format(name=name, package=name), encoding="utf-8")
        created.append(py_file)
    test_file = py_framework_dir / "tests" / f"test_plugin_{name}.py"
    if not test_file.exists():
        test_file.write_text(TEST_TEMPLATE.format(name=name, class_name=cls), encoding="utf-8")
        created.append(test_file)
    return created


# --------------------------------------------------------------------------- project level


def prepare_runtime(runtime: Any, config: Any, *, run_pub_get: bool = True) -> SyncResult:
    """Brings the project's Flutter runtime in line with ``pyflutter.yaml`` before `run` / `build`.

    ``runtime`` is a :class:`~pyflutter.core.runtime_project.ProjectRuntime`. It creates or
    refreshes the project copy of the runtime, installs the plugins and extra Flutter packages
    listed in ``config``, and writes the permissions (the ones of ``pyflutter.yaml`` plus the ones
    the plugins need) into the Android manifest and the iOS plist.
    """
    from pyflutter.cli.manifest_sync import sync_platform_metadata

    runtime.ensure()
    catalog = load_catalog(runtime.template_dir)
    catalog_packages = {e.package for e in catalog.values()}
    extras = {n: c for n, c in config.flutter_dependencies.items() if n not in catalog_packages}
    result = sync_plugins(
        runtime.runtime_dir, config.plugins,
        run_pub_get=run_pub_get, template_dir=runtime.template_dir, extra_dependencies=extras,
    )
    entries = expand_requirements(config.plugins, catalog)
    sync_platform_metadata(
        runtime.runtime_dir, config,
        extra_permissions=plugin_permissions(entries), extra_queries=plugin_queries(entries),
    )
    if result.files_changed:
        logger.info("Plugins synced: {}", ", ".join(result.plugins) or "(none)")
    return result


def resolved_version(runtime_dir: Path, package: str) -> Optional[str]:
    """The version `flutter pub get` locked for ``package`` in ``pubspec.lock`` (None if unknown)."""
    lock = Path(runtime_dir) / "pubspec.lock"
    if yaml is None or not lock.exists():
        return None
    try:
        data = yaml.safe_load(lock.read_text(encoding="utf-8")) or {}
        return str(data["packages"][package]["version"])
    except (KeyError, TypeError, ValueError):
        return None
